export function t(idioma: Idioma, clave: string): string {
  return UI[idioma][clave] ?? UI[IDIOMA_POR_DEFECTO][clave] ?? clave;
}

/** Rellena los huecos {nombre} de una cadena traducida. */
export function fmt(plantilla: string, valores: Record<string, string | number>): string {
  return plantilla.replace(/\{(\w+)\}/g, (hueco, k: string) =>
    k in valores ? String(valores[k]) : hueco,
  );
}

/** Las fechas se escriben día/mes/año en los cuatro idiomas: un 03/04 leído
    al revés en una urgencia es una vacuna caducada que parece válida. */
export function fecha(iso: string): string {
  const [a, m, d] = iso.slice(0, 10).split("-");
  return `${d}/${m}/${a}`;
}

export function especie(idioma: Idioma, codigo: string): string {
  return ESPECIES[idioma][codigo] ?? ESPECIES[IDIOMA_POR_DEFECTO][codigo] ?? codigo;
}

/** Las claves tienen que existir en los cuatro idiomas: lo comprueba el test. */
export function clavesQueFaltan(): string[] {
  const faltan: string[] = [];
  for (const tabla of [UI, ESPECIES, NIVELES, PASAPORTE]) {
    const base = Object.keys(tabla[IDIOMA_POR_DEFECTO]);
    for (const idioma of IDIOMAS) {
      for (const k of base) {
        if (!(k in tabla[idioma])) faltan.push(`${idioma}:${k}`);
      }
    }
  }
  return faltan;
}
